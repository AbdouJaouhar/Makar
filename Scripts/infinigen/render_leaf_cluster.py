"""
Renders a cluster of Infinigen leaves, seen from above, into textures for the leaf cards of the island's trees and
shrubs (Source/Makar/.../OceanFlora.cpp: each leaf mass of a crown is a handful of crossed cards showing this cluster).

Kinds, both Caribbean coastal species:
  broadleaf  LeafFactoryBroadleaf (summer) leaves in rosettes at the tips of a forked twig: the tropical almond
             (Terminalia catappa) and the other broadleaf trees behind the beaches;
  seagrape   LeafHeartFactory leaves, broad and round, along short zigzag stems: the sea grape (Coccoloba uvifera)
             that lines the top of the beaches.

Each leaf is generated by Infinigen (procedural blade, veins, colour), laid in a canonical frame (petiole at the
origin, blade along +X, face up +Z) by the principal axes of its vertices, then copied around the twig. The cluster is
rendered like the palm frond (render_frond_atlas.render_top_view): <kind>_basecolor.png (RGBA), <kind>_normal.png.

Run inside the Infinigen environment in WSL:
    python render_leaf_cluster.py <kind> <output folder> [resolution] [seed]
"""

import math
import os
import random
import sys

import bpy  # first: with bpy installed as a Python module, mathutils only exists once bpy is loaded
import mathutils
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from render_frond_atlas import render_top_view  # noqa: E402

# Per kind: leaf length (m) and layout. Rosettes: (centre in m, leaves, spread in degrees), leaves radiating from the
# centre (the tropical almond's leaves crowd at the twig tips). Stems: count of stems radiating from the centre and
# leaves per stem, alternate along it (the sea grape's zigzag stems).
KINDS = {
    "broadleaf": {"length": (0.2, 0.28), "rosettes": [((0.0, 0.0), 9, 360.0), ((-0.24, 0.17), 7, 300.0),
                                                       ((-0.22, -0.2), 7, 300.0), ((-0.42, 0.02), 5, 220.0)]},
    # LeafHeartFactory puts the heart's point at its origin: flipped so that the notch is at the petiole (cordate base).
    "seagrape": {"length": (0.13, 0.19), "stems": (6, 5), "flip": True},
}


def leaf_placements(config, rng):
    """(x, y, yaw in radians, length) of each leaf, drawn back to front."""
    placements = []
    if "rosettes" in config:
        for (cx, cy), count, spread in reversed(config["rosettes"]):
            start = rng.uniform(0.0, 360.0)
            for leaf_index in range(count):
                if spread >= 360.0:
                    yaw = start + 360.0 * (leaf_index + rng.uniform(-0.3, 0.3)) / count
                else:  # partial rosettes open towards the twig tip (+X)
                    yaw = -spread * 0.5 + spread * (leaf_index + 0.5 + rng.uniform(-0.3, 0.3)) / count
                placements.append((cx, cy, math.radians(yaw), rng.uniform(*config["length"])))
    else:
        stems, per_stem = config["stems"]
        start = rng.uniform(0.0, 2.0 * math.pi)
        for stem in range(stems):
            angle = start + 2.0 * math.pi * (stem + rng.uniform(-0.25, 0.25)) / stems
            direction = np.array([math.cos(angle), math.sin(angle)])
            side_axis = np.array([-direction[1], direction[0]])
            for leaf_index in range(per_stem):
                side = 1.0 if leaf_index % 2 == 0 else -1.0
                distance = 0.05 + leaf_index * rng.uniform(0.07, 0.09)
                x, y = direction * distance + side_axis * side * 0.015
                yaw = angle + side * math.radians(rng.uniform(40.0, 75.0))
                # Larger leaves near the base of the stem.
                length = rng.uniform(*config["length"]) * (1.1 - 0.06 * leaf_index)
                placements.append((x, y, yaw, length))
        rng.shuffle(placements)
    return placements


def make_factory(kind, seed):
    if kind == "broadleaf":
        from infinigen.assets.objects.leaves.leaf_broadleaf import LeafFactoryBroadleaf
        return LeafFactoryBroadleaf(seed, season="summer")
    from infinigen.assets.objects.small_plants.leaf_heart import LeafHeartFactory
    return LeafHeartFactory(seed)


def seagrape_material():
    """Sea grape leaf: Infinigen shades its heart leaves with a flat green (simple_greenery). Coccoloba uvifera
    leaves are leathery and glossy, yellow- to mid-green, with a pale midrib and side veins; a few old ones turn
    orange-red. Drawn in the leaf's canonical frame (object coordinates: petiole at 0, blade along +X), with a colour
    per leaf (Object Info > Random)."""
    material = bpy.data.materials.new("SeaGrapeLeaf")
    material.use_nodes = True
    nodes, links = material.node_tree.nodes, material.node_tree.links
    nodes.clear()

    def op(operation, a, b=None):
        node = nodes.new("ShaderNodeMath")
        node.operation = operation
        links.new(a, node.inputs[0]) if not isinstance(a, float) else setattr(node.inputs[0], "default_value", a)
        if b is not None:
            links.new(b, node.inputs[1]) if not isinstance(b, float) else setattr(node.inputs[1], "default_value", b)
        return node.outputs[0]

    def band(value, low, high):  # smoothstep from 1 (below low) to 0 (above high)
        node = nodes.new("ShaderNodeMapRange")
        node.interpolation_type = "SMOOTHSTEP"
        links.new(value, node.inputs["Value"])
        node.inputs["From Min"].default_value, node.inputs["From Max"].default_value = low, high
        node.inputs["To Min"].default_value, node.inputs["To Max"].default_value = 1.0, 0.0
        return node.outputs[0]

    def mix(factor, a, b, blend="MIX"):
        node = nodes.new("ShaderNodeMixRGB")
        node.blend_type = blend
        links.new(factor, node.inputs[0]) if not isinstance(factor, float) else setattr(node.inputs[0], "default_value", factor)
        for index, colour in ((1, a), (2, b)):
            if isinstance(colour, tuple):
                node.inputs[index].default_value = colour
            else:
                links.new(colour, node.inputs[index])
        return node.outputs[0]

    coords = nodes.new("ShaderNodeTexCoord").outputs["Object"]
    xyz = nodes.new("ShaderNodeSeparateXYZ")
    links.new(coords, xyz.inputs[0])
    across = op("ABSOLUTE", xyz.outputs["Y"])
    midrib = band(across, 0.006, 0.016)
    # Side veins leave the midrib forwards and curve out to the margin (phase bent by the square of the distance).
    curve = op("MULTIPLY", op("MULTIPLY", across, across), 2.5)
    side_phase = op("FRACT", op("MULTIPLY", op("SUBTRACT", op("SUBTRACT", xyz.outputs["X"], op("MULTIPLY", across, 0.8)), curve), 4.5))
    side = op("SUBTRACT", 1.0, band(op("ABSOLUTE", op("SUBTRACT", side_phase, 0.5)), 0.465, 0.495))
    veins = op("MAXIMUM", midrib, op("MULTIPLY", side, 0.2))

    ramp_node = nodes.new("ShaderNodeValToRGB")
    links.new(nodes.new("ShaderNodeObjectInfo").outputs["Random"], ramp_node.inputs[0])
    ramp = ramp_node.color_ramp
    ramp.elements[0].position, ramp.elements[0].color = 0.0, (0.09, 0.2, 0.035, 1.0)
    ramp.elements[1].position, ramp.elements[1].color = 0.55, (0.17, 0.33, 0.06, 1.0)
    for position, colour in ((0.82, (0.27, 0.37, 0.07, 1.0)), (0.88, (0.42, 0.24, 0.05, 1.0)), (1.0, (0.48, 0.11, 0.04, 1.0))):
        element = ramp.elements.new(position)
        element.color = colour
    noise = nodes.new("ShaderNodeTexNoise")
    noise.inputs["Scale"].default_value = 9.0
    links.new(coords, noise.inputs["Vector"])
    mottled = mix(0.25, ramp_node.outputs["Color"], noise.outputs["Color"], "MULTIPLY")
    colour = mix(op("MULTIPLY", veins, 0.7), mottled, (0.52, 0.36, 0.26, 1.0))  # pale, reddish midrib

    bsdf = nodes.new("ShaderNodeBsdfPrincipled")
    links.new(colour, bsdf.inputs["Base Color"])
    bsdf.inputs["Roughness"].default_value = 0.35
    output = nodes.new("ShaderNodeOutputMaterial")
    links.new(bsdf.outputs[0], output.inputs["Surface"])
    return material


def canonical_leaf(obj, flip=False):
    """The leaf's evaluated mesh, moved to the canonical frame: petiole at the origin (the end nearest to the
    object's origin, or the other one with flip), blade along +X, face up +Z, length 1. Returns the mesh."""
    depsgraph = bpy.context.evaluated_depsgraph_get()
    mesh = bpy.data.meshes.new_from_object(obj.evaluated_get(depsgraph), preserve_all_data_layers=True, depsgraph=depsgraph)
    mesh.transform(obj.matrix_world)
    points = np.empty(len(mesh.vertices) * 3, dtype=np.float64)
    mesh.vertices.foreach_get("co", points)
    points = points.reshape(-1, 3)
    center = points.mean(axis=0)
    _, _, axes = np.linalg.svd(points - center, full_matrices=False)
    length_axis, normal_axis = axes[0], axes[2]
    # The petiole is the end nearest to the object's origin (where Infinigen attaches the leaf).
    origin = np.asarray(obj.matrix_world.translation)
    projections = (points - center) @ length_axis
    if (np.dot(origin - center, length_axis) > 0.0) != flip:
        length_axis = -length_axis
        projections = -projections
    # Face up: the polygons' normals mostly along +normal_axis.
    normals = np.empty(len(mesh.polygons) * 3, dtype=np.float64)
    mesh.polygons.foreach_get("normal", normals)
    if normals.reshape(-1, 3).sum(axis=0) @ normal_axis < 0.0:
        normal_axis = -normal_axis
    width_axis = np.cross(normal_axis, length_axis)
    rotation = np.stack([length_axis, width_axis, normal_axis])  # rows: new X, Y, Z
    base = center + length_axis * projections.min()
    length = float(projections.max() - projections.min())
    flat = (points - base) @ rotation.T / length
    mesh.vertices.foreach_set("co", flat.astype(np.float32).ravel())
    mesh.update()
    return mesh


def main(kind, out_dir, resolution, seed):
    config = KINDS[kind]
    rng = random.Random(seed)
    bpy.ops.wm.read_factory_settings(use_empty=True)
    factory = make_factory(kind, seed)

    # A few distinct leaves, canonical.
    leaves = []
    own_material = seagrape_material() if kind == "seagrape" else None
    for index in range(4):
        obj = factory.spawn_asset(index)
        mesh = canonical_leaf(obj, config.get("flip", False))
        if own_material:
            mesh.materials.clear()
            mesh.materials.append(own_material)
        leaves.append(mesh)
        for o in list(bpy.context.scene.objects):
            bpy.data.objects.remove(o, do_unlink=True)
    print(f"render_leaf_cluster: {len(leaves)} {kind} leaves, materials {[m.name for m in leaves[0].materials if m]}")

    # The cluster: each leaf from its attachment point, tilted down (drooping outwards) and rolled a little.
    low = np.array([1e9, 1e9, 1e9])
    high = -low
    for order, (x, y, yaw, length) in enumerate(leaf_placements(config, rng)):
        pitch = math.radians(rng.uniform(8.0, 28.0))
        roll = math.radians(rng.uniform(-20.0, 20.0))
        matrix = (mathutils.Matrix.Translation((x, y, 0.001 * order))  # later leaves on top
                  @ mathutils.Matrix.Rotation(yaw, 4, "Z")
                  @ mathutils.Matrix.Rotation(pitch, 4, "Y")
                  @ mathutils.Matrix.Rotation(roll, 4, "X")
                  @ mathutils.Matrix.Scale(length, 4))
        obj = bpy.data.objects.new("Leaf", rng.choice(leaves))
        obj.matrix_world = matrix
        bpy.context.scene.collection.objects.link(obj)
        corners = np.array([matrix @ mathutils.Vector(c) for c in ((0, -0.45, 0), (1, -0.45, 0), (1, 0.45, 0), (0, 0.45, 0))])
        low = np.minimum(low, corners.min(axis=0))
        high = np.maximum(high, corners.max(axis=0))

    scene = bpy.context.scene
    scene.world = bpy.data.worlds.new("World")
    span, mid = render_top_view(out_dir, kind, resolution, low, high)
    print(f"render_leaf_cluster: {kind} cluster {span:.2f} m wide -> {out_dir}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], int(sys.argv[3]) if len(sys.argv) > 3 else 2048, int(sys.argv[4]) if len(sys.argv) > 4 else 0)
