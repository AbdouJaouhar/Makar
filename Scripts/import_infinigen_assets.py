"""
Imports procedural assets generated by Infinigen (princeton-vl/infinigen, BSD-3) into /Game/Ocean/Infinigen.

Infinigen runs in WSL2 (Scripts/infinigen/generate_assets.sh): it generates each object procedurally in Blender,
bakes its materials to textures and exports one FBX per object. This script imports every FBX found under the
export folder, one content folder per category (the export's sub-folder name), as Nanite static meshes with their
baked textures.

Run from the editor (Tools > Execute Python Script...) or headless:
    UnrealEditor-Cmd.exe Makar.uproject -run=pythonscript -script=Scripts/import_infinigen_assets.py
Exports are copied from WSL (/root/makar/generated/<category>/export_NNN/) into Saved/Infinigen/<category>/ first
(Scripts/infinigen/fetch_exports.ps1); override the folder with the MAKAR_INFINIGEN_EXPORT environment variable.
"""

import os

import unreal

EXPORT_ROOT = os.environ.get("MAKAR_INFINIGEN_EXPORT", os.path.join(unreal.Paths.project_saved_dir(), "Infinigen"))
DESTINATION = "/Game/Ocean/Infinigen"


def import_fbx(path, destination):
    options = unreal.FbxImportUI()
    options.set_editor_property("import_mesh", True)
    options.set_editor_property("import_as_skeletal", False)
    options.set_editor_property("import_materials", True)
    options.set_editor_property("import_textures", True)
    options.set_editor_property("mesh_type_to_import", unreal.FBXImportType.FBXIT_STATIC_MESH)
    mesh_options = options.get_editor_property("static_mesh_import_data")
    mesh_options.set_editor_property("combine_meshes", True)  # one asset per object (Infinigen splits parts)
    mesh_options.set_editor_property("build_nanite", True)
    mesh_options.set_editor_property("generate_lightmap_u_vs", False)
    mesh_options.set_editor_property("auto_generate_collision", False)
    # Infinigen exports in metres, Z up.
    mesh_options.set_editor_property("import_uniform_scale", 100.0)

    task = unreal.AssetImportTask()
    task.set_editor_property("filename", path)
    task.set_editor_property("destination_path", destination)
    task.set_editor_property("automated", True)
    task.set_editor_property("replace_existing", True)
    task.set_editor_property("save", True)
    task.set_editor_property("options", options)
    unreal.AssetToolsHelpers.get_asset_tools().import_asset_tasks([task])
    return task.get_editor_property("imported_object_paths")


def main():
    if not os.path.isdir(EXPORT_ROOT):
        raise RuntimeError(f"Infinigen export folder not found: {EXPORT_ROOT}")
    # The folder only holds what this script imports: start clean so removed or renamed assets do not linger.
    if unreal.EditorAssetLibrary.does_directory_exist(DESTINATION):
        unreal.EditorAssetLibrary.delete_directory(DESTINATION)
    imported = 0
    for folder, _, files in os.walk(EXPORT_ROOT):
        for name in sorted(files):
            if not name.lower().endswith(".fbx"):
                continue
            category = os.path.relpath(folder, EXPORT_ROOT).split(os.sep)[0]
            category = "".join(c if c.isalnum() else "_" for c in category) or "Misc"
            paths = import_fbx(os.path.join(folder, name), f"{DESTINATION}/{category}")
            unreal.log(f"Infinigen: {name} -> {list(paths)}")
            imported += 1
    unreal.log(f"Infinigen: {imported} FBX imported into {DESTINATION}")


main()
